"""Pydantic schemas for TrailBuddy Local outdoor missions and journals.

Enforces strict validation, field boundaries, and safe outdoor activity constraints.
"""

from datetime import datetime
from typing import List, Optional, Literal
from uuid import uuid4
from pydantic import BaseModel, Field, field_validator


ALLOWED_DURATIONS = [10, 20, 30]
ALLOWED_INTERESTS = [
    "nature",
    "plants",
    "birds",
    "mindfulness",
    "photography",
    "general exploration",
]
ALLOWED_DIFFICULTIES = ["easy", "moderate", "challenging"]
ALLOWED_ENVIRONMENTS = [
    "garden",
    "park",
    "neighborhood",
    "any accessible outdoor space",
]


class MissionRequest(BaseModel):
    """Input parameters provided by the user to request a personalized mission."""

    duration_minutes: int = Field(
        ...,
        description="Available outdoor time in minutes (10, 20, or 30).",
    )
    interest: str = Field(
        ...,
        description="User interest category.",
    )
    difficulty: str = Field(
        ...,
        description="Activity difficulty level.",
    )
    environment: str = Field(
        ...,
        description="Outdoor environment.",
    )
    accessibility: Optional[str] = Field(
        default=None,
        description="Optional accessibility or mobility considerations.",
    )

    @field_validator("duration_minutes")
    @classmethod
    def validate_duration(cls, v: int) -> int:
        if v not in ALLOWED_DURATIONS:
            raise ValueError(f"duration_minutes must be one of {ALLOWED_DURATIONS}, got {v}")
        return v

    @field_validator("interest")
    @classmethod
    def validate_interest(cls, v: str) -> str:
        clean = v.strip().lower()
        if clean not in ALLOWED_INTERESTS:
            raise ValueError(f"interest must be one of {ALLOWED_INTERESTS}, got '{v}'")
        return clean

    @field_validator("difficulty")
    @classmethod
    def validate_difficulty(cls, v: str) -> str:
        clean = v.strip().lower()
        if clean not in ALLOWED_DIFFICULTIES:
            raise ValueError(f"difficulty must be one of {ALLOWED_DIFFICULTIES}, got '{v}'")
        return clean

    @field_validator("environment")
    @classmethod
    def validate_environment(cls, v: str) -> str:
        clean = v.strip().lower()
        if clean not in ALLOWED_ENVIRONMENTS:
            raise ValueError(f"environment must be one of {ALLOWED_ENVIRONMENTS}, got '{v}'")
        return clean


class Mission(BaseModel):
    """Structured, validated outdoor mission generated by local AI."""

    id: str = Field(default_factory=lambda: str(uuid4()))
    title: str = Field(
        ...,
        min_length=3,
        max_length=120,
        description="Engaging title for the outdoor mission.",
    )
    description: str = Field(
        ...,
        min_length=10,
        max_length=600,
        description="Short description setting the context.",
    )
    duration_minutes: int = Field(
        ...,
        gt=0,
        le=120,
        description="Estimated duration in minutes.",
    )
    tasks: List[str] = Field(
        ...,
        min_length=3,
        max_length=5,
        description="Three to five actionable, offline outdoor tasks.",
    )
    required_items: List[str] = Field(
        default_factory=list,
        description="Optional simple, low-cost household items (e.g. water, notebook).",
    )
    safety_reminders: List[str] = Field(
        ...,
        min_length=1,
        description="Essential safety tips suitable for the selected environment.",
    )
    reflection_question: Optional[str] = Field(
        default=None,
        description="Optional mindful reflection question for after the mission.",
    )
    completed: bool = Field(
        default=False,
        description="Whether the mission was marked complete by the user.",
    )
    completed_at: Optional[str] = Field(
        default=None,
        description="ISO timestamp when marked complete.",
    )
    user_reflection: Optional[str] = Field(
        default=None,
        description="Optional personal journal reflection entered by the user.",
    )
    created_at: str = Field(
        default_factory=lambda: datetime.now().isoformat(),
        description="ISO creation timestamp.",
    )

    @field_validator("tasks")
    @classmethod
    def validate_tasks(cls, v: List[str]) -> List[str]:
        cleaned = [t.strip() for t in v if t and t.strip()]
        if len(cleaned) < 3 or len(cleaned) > 5:
            raise ValueError(f"Mission must contain between 3 and 5 tasks, got {len(cleaned)}")
        return cleaned

    @field_validator("safety_reminders")
    @classmethod
    def validate_safety(cls, v: List[str]) -> List[str]:
        cleaned = [s.strip() for s in v if s and s.strip()]
        if len(cleaned) < 1:
            raise ValueError("Mission must include at least one safety reminder.")
        return cleaned


class JournalEntry(BaseModel):
    """Journal entry recorded in local SQLite database."""

    id: Optional[int] = None
    mission_id: Optional[str] = None
    mission_title: str = Field(..., min_length=1)
    date_completed: str = Field(..., description="ISO or readable date string")
    duration_minutes: int = Field(..., gt=0)
    reflection: Optional[str] = None
    completed: bool = True
